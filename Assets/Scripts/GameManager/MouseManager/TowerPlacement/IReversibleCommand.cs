/// 임시로 실행해 두었다가 되돌리거나(Undo) 확정할(Commit) 수 있는 조작(#263).
///
/// 일반 Command의 Execute/Undo 2단이 아니라 **3단인 이유**: "실행했지만 아직 되돌릴 수 있는 상태"와
/// "확정되어 더는 되돌릴 수 없는 상태"를 구분해야 하기 때문이다. 트랜잭션에 가깝다.
/// 합성이 이걸 필요로 한 경위 — 재료를 클릭 즉시 소모해 타일을 비우되(그래야 그 자리에 결과를 놓는다),
/// 배치를 취소하면 되돌려야 한다. 확정되면 그때 진짜로 파괴한다.
///
/// **전역 Undo 스택을 두지 않는다.** 진행 중인 커맨드는 항상 최대 1개이기 때문인데, 그것을 떠받치는
/// 것은 `MouseManager.BeginPlacement`가 **새 세션을 열기 전에 `CancelPlacement`를 먼저 부른다**는
/// 사실이다 — 그 취소가 이전 세션의 종료 콜백(=이전 커맨드의 `Undo`)을 발화시키므로, 새 커맨드가
/// 자리를 잡는 시점엔 이전 커맨드가 이미 해소돼 있다. (`TowerPlacer.keepPlacing`은 이 보장과 무관하다 —
/// 켜져 있어도 확정된 커맨드는 `Committed`라 pending이 아니다. WL-105는 별개 축이다.)
/// 되돌릴 수 있는 조작이 더 생기면(건물 철거 등) 그때 히스토리 도입을 검토한다.
///
/// **위치**: 이름은 범용이지만 지금은 합성 전용이라 실행부와 같은 폴더에 둔다(전역 네임스페이스도 유지 —
/// 프로젝트 컨벤션). 두 번째 구현체(경영 철거 등)가 생기는 시점에 중립 위치로 옮긴다 — WL-085와 같은 축.
public interface IReversibleCommand
{
    /// 조작을 임시로 실행한다. 실패 시 false — 이때 **아무것도 바뀌지 않아야 한다**
    /// (호출부가 실패 후 원복을 고민할 필요가 없다는 계약).
    bool Execute();

    /// 실행 결과를 확정한다. 이 뒤의 Undo는 무시된다.
    void Commit();

    /// Execute를 되돌린다. 확정된 뒤라면 무시된다.
    void Undo();
}
