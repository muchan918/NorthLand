/// <summary>
/// <b>비활성 상태로 눌린 버튼이 스스로 낼 피드백.</b> <see cref="UiClickSfx"/>가 찾아 호출한다.
///
/// ── 왜 필요한가 ──────────────────────────────────────────────────
///
/// <c>Button.interactable == false</c>인 버튼을 누르면 <b>어느 경로도 지나지 않는다</b> —
/// <c>onClick</c>은 아예 발화하지 않고, <see cref="UiClickSfx"/>의 전역 훅도
/// <c>Selectable.IsInteractable()</c>에서 빠진다. 그래서 회색 버튼은 눌러도 화면에서든 소리에서든
/// <b>아무 일도 안 일어난 것처럼 보인다</b> — 스킬 쿨다운 중 버튼 연타가 실제로 그랬다(#550).
///
/// 버튼을 계속 활성으로 두고 핸들러에서 반려하는 방향은 택하지 않았다. 회색 처리 자체가
/// "지금은 못 쓴다"는 표시라 그걸 잃으면 손해가 더 크다.
///
/// ── 왜 인터페이스인가 ────────────────────────────────────────────
///
/// <see cref="ICursorHint"/>와 같은 판단이다 — <b>무슨 피드백을 낼지는 대상이 안다.</b>
/// 전역 훅이 "이건 스킬 버튼인가"를 분기하기 시작하면 버튼 종류마다 조건이 하나씩 박힌다.
/// 구현체가 없는 버튼은 지금처럼 조용히 넘어간다(회색 버튼 대부분이 그렇다).
/// </summary>
public interface IDisabledClickFeedback
{
    /// <summary>
    /// 이 버튼이 비활성 상태로 눌렸다. <b>눌린 프레임에</b> 불린다(뗄 때가 아니라 —
    /// <see cref="UiClickSfx"/>의 공용 클릭음과 같은 시점).
    ///
    /// 소리를 낼지 말지는 구현체가 판단한다. 비활성 사유가 여러 가지일 때 그중 일부에만
    /// 안내음이 어울리는 경우가 있다(스킬 버튼: 충전 소진에만 낸다).
    ///
    /// ── ⚠ 구현 제약: 소리·연출만. 게임 상태를 바꾸지 말 것 ──────────
    ///
    /// <b>선택·배치·모드 전환·자원·페이즈 등 어떤 게임 상태도 건드리지 않는다.</b> 툴팁을 띄우거나
    /// 패널을 여는 것도 안 된다 — 그것도 상태다.
    ///
    /// 이 제약은 취향이 아니라 <b><see cref="UiClickSfx"/>가 존재할 수 있는 근거</b>다.
    /// `SystemMap.md` 팀 계약 #1은 게임플레이 코드의 <c>Mouse.current</c> 직접 폴링을 금지하면서
    /// <see cref="UiClickSfx"/>를 넷째 예외로 두는데, <b>그 예외의 조건이 "게임 상태를 바꾸지 않는다"
    /// 하나</b>이고 "이 예외를 근거로 삼으려면 상태 불변을 먼저 만족해야 한다"고 못 박혀 있다.
    /// 이 메서드는 그 폴링 경로 위에서 실행되므로, 구현체가 상태를 바꾸는 순간 예외의 전제가 무너진다.
    ///
    /// 상태를 바꿔야 하는 반응이 필요하면 이 훅이 아니라 <c>MouseManager</c> 라우팅으로 간다.
    /// 구현체가 여럿 생긴 뒤에 되돌리는 것은 훨씬 비싸다.
    /// </summary>
    void OnDisabledClick();
}
