/// 실행해 두었다가 되돌리거나(Undo) 확정할(Commit) 수 있는 조작(#263 → #281).
///
/// 일반 Command의 Execute/Undo 2단이 아니라 **4단인 이유**: "실행했다", "세션이 성공으로 끝났다",
/// "더는 되돌릴 수 없다"가 서로 다른 시점이기 때문이다. 트랜잭션에 가깝다.
/// 합성이 이걸 필요로 한 경위 — 재료를 클릭 즉시 소모해 타일을 비우되(그래야 그 자리에 결과를 놓는다),
/// 배치를 취소하면 되돌려야 한다. 확정되면 그때 진짜로 파괴한다.
///
/// **#281에서 `Commit`이 겸하던 두 뜻을 쪼갰다.** 예전의 `Commit`은 "세션이 확정으로 끝났다"와
/// "더는 되돌릴 수 없다"를 동시에 의미했다. 되돌리기 히스토리를 넣으려면 후자를 밤까지 미뤄야 하는데,
/// 시점만 옮기면 배치 세션 종료 통지가 **항상 취소로 오인돼** 확정한 합성이 되감긴다(무료 합성 버그).
/// 그래서 전자를 `Confirm`으로 떼어냈다.
///
/// **진행 중(Executed) 커맨드는 여전히 항상 최대 1개다.** 그것을 떠받치는 것은
/// `MouseManager.BeginPlacement`가 **새 세션을 열기 전에 `CancelPlacement`를 먼저 부른다**는 사실이다 —
/// 그 취소가 이전 세션의 종료 콜백(=이전 커맨드의 `Undo`)을 발화시키므로, 새 커맨드가 자리를 잡는
/// 시점엔 이전 커맨드가 이미 해소돼 있다. `Confirm`을 지난 커맨드는 `CommandHistory` 스택으로 넘어가므로
/// 이 불변식과 무관하다 — **진행 중인 것과 히스토리에 쌓인 것은 겹치지 않는 두 집합이고**, 그 사실이
/// 밤 진입 시 `CommandHistory.CommitAll`과 `PhasePanelSwitcher.ShowNight`의 구독 순서를 무의미하게 만든다.
/// (`TowerPlacer.keepPlacing`은 이 보장과 무관하다 — WL-105는 별개 축이다.)
///
/// **되돌리기는 LIFO여야 한다** — 이건 편의가 아니라 정확성 요건이다. `A 배치(tile1) → A+B 합성 →
/// C를 (비워진) tile1에 배치` 상태에서 합성을 먼저 되돌리면 A가 tile1을 되찾지 못하고
/// `TowerFootprint.Reoccupy`가 그 타일을 목록에서 빼버려 **A는 타일 없는 타워가 된다**. LIFO가 C를
/// 먼저 되돌리게 강제해 이 경로를 원천 차단한다 — 즉 LIFO 자체가 유효성 검사다.
/// ⚠ 낮 중 타워 철거·사망처럼 **히스토리를 거치지 않고 대상이 사라지는 경로**가 생기면 이 불변식이
/// 깨진다. 그때는 각 커맨드에 대상 유효성 검사를 따로 넣어야 한다(지금은 null 방어까지만 한다).
///
/// **위치**: 구현체가 둘(합성·배치)이 되면서 중립 위치(`Assets/Scripts/Command/`)로 옮겼다 —
/// 이전 파일에 예고돼 있던 그 시점이다. 전역 네임스페이스는 프로젝트 컨벤션대로 유지한다.
public interface IReversibleCommand
{
    /// 조작을 실행한다. 실패 시 false — 이때 **아무것도 바뀌지 않아야 한다**
    /// (호출부가 실패 후 원복을 고민할 필요가 없다는 계약).
    bool Execute();

    /// 세션이 성공으로 끝났음을 알린다. **상태 전이만 한다 — 되돌리기는 여전히 가능하다.**
    /// 히스토리 등록 시점이기도 하다(`CommandHistory.Push`가 이걸 부른다).
    void Confirm();

    /// 되돌리기 불가로 확정한다. 소프트 소모해 둔 것이 있으면 여기서 **진짜로** 파괴한다.
    /// 밤 진입 시 히스토리 전체에 걸린다.
    void Commit();

    /// 조작을 되돌린다. `Executed`(진행 중 세션 취소)와 `Confirmed`(되돌리기 버튼) 양쪽에서 동작하고,
    /// `Commit` 이후라면 무시된다.
    void Undo();

    /// 세션이 성공으로 끝났는가. 배치 세션 종료 통지(`TowerPlacer`의 OnEnded)는 **확정으로 끝났는지
    /// 취소로 끝났는지를 알려주지 않으므로**, 그 판단을 커맨드가 자기 상태로 한다. 덕분에
    /// `TowerPlacer`/`MouseManager`의 배치 코어를 건드리지 않고도 "취소일 때만 원복"이 성립한다.
    bool IsConfirmed { get; }
}
